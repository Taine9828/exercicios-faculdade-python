##Crie um programa em Python que solicite duas notas de um aluno, calcule a média aritmética entre elas e mostre o resultado na tela.

nota1 = float(input("Digite a primeiro nota do aluno:"))
nota2 = float(input("Digite a segunda nota do aluno:"))
soma = nota1 + nota2 
media = soma / 2
print (f"A media das notas é: {media}")
